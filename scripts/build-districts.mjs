// Builds src/lib/geo/districts.ts — India's districts (name, state, label point) for the map — from GeoNames
// (https://www.geonames.org, CC BY 4.0, already credited under the map).
//
//   curl -O https://download.geonames.org/export/dump/IN.zip && unzip IN.zip
//   curl -O https://download.geonames.org/export/dump/admin1CodesASCII.txt
//   node scripts/build-districts.mjs IN.txt admin1CodesASCII.txt
import { readFileSync, writeFileSync } from 'node:fs';

const [inFile, admin1File] = process.argv.slice(2);
if (!inFile || !admin1File) { console.error('usage: node scripts/build-districts.mjs IN.txt admin1CodesASCII.txt'); process.exit(1); }
const states = new Map(readFileSync(admin1File, 'utf8').split('\n').filter((l) => l.startsWith('IN.'))
  .map((l) => l.split('\t')).map(([code, name]) => [code.slice(3), name]));
const clean = (s) => s.replace(/^(District|Zila|Jila)\s+/i, '').replace(/\s+(District|district|Division)$/, '').replace(/\s+/g, ' ').trim();
const rows = readFileSync(inFile, 'utf8').split('\n').map((l) => l.split('\t')).filter((c) => c[7] === 'ADM2');
const out = rows.map((c) => [clean(c[2] || c[1]), states.get(c[10]) || '', Math.round(Number(c[4]) * 100) / 100, Math.round(Number(c[5]) * 100) / 100])
  .filter(([n, s, lat, lng]) => n && s && Number.isFinite(lat) && Number.isFinite(lng))
  .sort((a, b) => a[1].localeCompare(b[1]) || a[0].localeCompare(b[0]));
const body = `/* AUTO-GENERATED by scripts/build-districts.mjs from GeoNames (https://www.geonames.org), CC BY 4.0 —
 * do not edit by hand; re-run the script instead. ${out.length} districts: [name, state, lat, lng] (label point).
 */
export const DISTRICTS: [name: string, state: string, lat: number, lng: number][] = [
${out.map((r) => `  ${JSON.stringify(r)},`).join('\n')}
];
`;
writeFileSync('src/lib/geo/districts.ts', body);
console.log(`wrote ${out.length} districts`);
