// Builds src/lib/geo/places.ts — India's towns and cities (population 1,000+ and administrative seats) with
// their state, for naming where a photo was taken, offline. From GeoNames (https://www.geonames.org, CC BY 4.0,
// already credited under the map).
//   curl -O https://download.geonames.org/export/dump/IN.zip && unzip IN.zip
//   curl -O https://download.geonames.org/export/dump/admin1CodesASCII.txt
//   node scripts/build-places.mjs IN.txt admin1CodesASCII.txt
import { readFileSync, writeFileSync } from 'node:fs';

const [inFile, admin1File] = process.argv.slice(2);
if (!inFile || !admin1File) { console.error('usage: node scripts/build-places.mjs IN.txt admin1CodesASCII.txt'); process.exit(1); }
const states = new Map(readFileSync(admin1File, 'utf8').split('\n').filter((l) => l.startsWith('IN.'))
  .map((l) => l.split('\t')).map(([code, name]) => [code.slice(3), name]));
const stateNames = [...new Set(states.values())].sort();
const rows = readFileSync(inFile, 'utf8').split('\n').map((l) => l.split('\t'))
  .filter((c) => c[6] === 'P' && (Number(c[14]) >= 1000 || /^PPL(A|A2|A3|A4|C)$/.test(c[7])));
const seen = new Set();
const out = [];
for (const c of rows.sort((a, b) => Number(b[14]) - Number(a[14]))) {
  const name = (c[2] || c[1]).trim();
  const st = states.get(c[10]);
  const lat = Math.round(Number(c[4]) * 1000) / 1000, lng = Math.round(Number(c[5]) * 1000) / 1000;
  if (!name || !st || !Number.isFinite(lat)) continue;
  const k = `${name}|${Math.round(lat * 20)}|${Math.round(lng * 20)}`; // one per name in a ~5 km cell
  if (seen.has(k)) continue;
  seen.add(k);
  out.push([name, stateNames.indexOf(st), lat, lng, Number(c[14]) || 0]);
}
const body = `/* AUTO-GENERATED by scripts/build-places.mjs from GeoNames (https://www.geonames.org), CC BY 4.0 —
 * do not edit by hand. ${out.length} towns and cities of India (population 1,000+ or a district/sub-district seat):
 * [name, state index into PLACE_STATES, lat, lng, population].
 */
export const PLACE_STATES: string[] = ${JSON.stringify(stateNames)};
export const PLACES: [string, number, number, number, number][] = [
${out.map((r) => `  ${JSON.stringify(r)},`).join('\n')}
];
`;
writeFileSync('src/lib/geo/places.ts', body);
console.log(`wrote ${out.length} places`);
